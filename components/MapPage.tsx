function getProvinceFromCity(location: string): string | null {
  // 1. Direct city match
  if (CITY_TO_PROVINCE[location]) return CITY_TO_PROVINCE[location];
  // 2. Location contains a known city
  for (const [city, province] of Object.entries(CITY_TO_PROVINCE)) {
    if (location.includes(city)) return province;
  }
  // 3. Try splitting compound names (e.g. "恩施利川" -> ["恩施", "利川"])
  for (const [city, province] of Object.entries(CITY_TO_PROVINCE)) {
    if (location.split(/[,，、\s]+/).some(part => part.includes(city))) return province;
  }
  // 4. Location contains a province name
  for (const [pattern, province] of Object.entries(PROVINCE_PATTERNS)) {
    if (location.includes(pattern)) return province;
  }
  // 5. Try matching by province in parentheses or after dash
  const match = location.match(/[（(]([^)）]+)[)）]/);
  if (match && PROVINCE_PATTERNS[match[1]]) return PROVINCE_PATTERNS[match[1]];
  return null;
}

function getEChartsName(province: string): string {
  return PROVINCE_NAME_MAP[province] || province;
}

